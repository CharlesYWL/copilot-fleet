// Builds the installable skill folder at packages/prm-skill/dist/prm:
/* global process */
//   SKILL.md, references/, schemas/*.json (generated), scripts/prm.mjs (bundled).
// The bundle inlines zod, @fleet/protocol and Fleet's read-only provider
// helpers, so the installed skill needs only Node >= 22 and gh / az.
import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { z } from "zod";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "dist", "prm");

/**
 * Fleet's helpers end with `if (process.argv[1] && import.meta.url === ...) main()`.
 * Inside one bundle every module shares the bundle's URL, so those guards would
 * all fire. Disable them; prm's own main.ts is the only entry point.
 */
const ENTRY_GUARD = /if \(process\.argv\[1\] && import\.meta\.url ===/g;
const disableReusedEntryPoints = {
  name: "disable-reused-entry-points",
  setup(context) {
    context.onLoad(
      { filter: /skills[\\/]pr-maintenance[\\/][^\\/]+\.mjs$/ },
      async (args) => {
        const source = await readFile(args.path, "utf8");
        const matches = source.match(ENTRY_GUARD)?.length ?? 0;
        if (
          /(?:snapshot|github-snapshot|ado-snapshot)\.mjs$/.test(args.path) &&
          matches !== 1
        )
          throw new Error(
            `Expected one CLI entry guard in ${args.path}, found ${matches}.`,
          );
        return {
          contents: source.replace(ENTRY_GUARD, "if (false && import.meta.url ==="),
          loader: "js",
        };
      },
    );
  },
};

await rm(out, { recursive: true, force: true });
await mkdir(join(out, "scripts"), { recursive: true });
await mkdir(join(out, "schemas"), { recursive: true });

await build({
  entryPoints: [join(here, "src", "main.ts")],
  outfile: join(out, "scripts", "prm.mjs"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  legalComments: "none",
  plugins: [disableReusedEntryPoints],
  banner: {
    js: [
      "// prm: portable PR-maintenance helper. Generated by packages/prm-skill/build.mjs; do not edit.",
      "import { createRequire as __prmCreateRequire } from 'node:module';",
      "const require = __prmCreateRequire(import.meta.url);",
    ].join("\n"),
  },
  logLevel: "warning",
});

// Bundle a throwaway module so schemas come from exactly the compiled contracts.
const schemaModule = join(here, "dist", "contracts.tmp.mjs");
await build({
  entryPoints: [join(here, "src", "contracts.ts")],
  outfile: schemaModule,
  bundle: true,
  platform: "node",
  format: "esm",
  external: ["zod"],
  logLevel: "warning",
});
const contracts = await import(`file://${schemaModule.replace(/\\/g, "/")}`);
for (const [name, schema] of Object.entries(contracts.PUBLISHED_SCHEMAS)) {
  const json = z.toJSONSchema(schema, {
    target: "draft-2020-12",
    io: "input",
    unrepresentable: "any",
  });
  await writeFile(join(out, "schemas", name), `${JSON.stringify(json, null, 2)}\n`);
}
await rm(schemaModule, { force: true });

await cp(join(here, "skill"), out, { recursive: true });
process.stdout.write(`Built ${out}\n`);
